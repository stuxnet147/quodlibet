/* The supported compiler and target matrix, checked against the corpus that
   defines it.

   ARCHITECTURE.md and METHODS.md both state the ASM2C_GNU_V1 provenance
   matrix: GCC and Clang, PIC and non-PIC, O0 through O3. The corpus is what
   that sentence is about, and the corpus is regenerated outside this
   repository. So the sentence can quietly stop being true - a new compiler or
   a new optimization level appears in the dataset and nothing here notices
   that the profile no longer covers what it claims to.

   This reads the dataset manifest and compares it against what the profile
   actually declares. Two directions matter and they fail differently:

     - the corpus grew a compiler or a codegen mode the profile does not
       cover, which means proofs are being asked for inputs outside the frozen
       provenance;
     - the profile declares an axis the corpus does not exercise, which is not
       a defect but is worth stating, because an unexercised axis is an
       untested claim.

   Optimization level is deliberately not a contract axis. ARCHITECTURE.md
   calls it validation provenance rather than a semantic switch, so the check
   is that the manifest's levels stay inside the documented range, not that
   some field encodes them. */

